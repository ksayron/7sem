class Page:
    def __init__(self, file, slug, title, subtitle):
        self.slug, self.title = slug, title
        dia = ET.SubElement(file, 'diagram', id=slug, name=title)
        model = ET.SubElement(dia, 'mxGraphModel', dx='1400', dy='990', grid='1', gridSize='10',
           guides='1', tooltips='1', connect='1', arrows='1', fold='1', page='1',
           pageScale='1', pageWidth='1400', pageHeight='990', math='0', shadow='0')
        self.root = ET.SubElement(model,'root')
        ET.SubElement(self.root,'mxCell',id='0')
        ET.SubElement(self.root,'mxCell',id='1',parent='0')
        self.nodes, self.count = {}, 0
        self.box('title', title, 35,20,1330,35,'text',24,True)
        self.box('subtitle', subtitle,35,58,1330,30,'text',18)

    def box(self, ident, value, x,y,w,h, kind='uc', size=19, bold=False):
        styles = {'uc':'ellipse;whiteSpace=wrap;', 'actor':'shape=umlActor;verticalLabelPosition=bottom;verticalAlign=top;outlineConnect=0;',
          'boundary':'rounded=0;align=center;verticalAlign=top;spacingTop=12;',
          'text':'text;strokeColor=none;fillColor=none;align=center;whiteSpace=wrap;',
          'note':'shape=note;whiteSpace=wrap;align=left;spacing=12;'}
        style=styles[kind] + f'html=1;fontFamily=Times New Roman;fontSize={size};fontColor=#000000;strokeColor=#000000;fillColor=#ffffff;strokeWidth=1.4;'
        if bold: style+='fontStyle=1;'
        if kind=='text': style+='strokeColor=none;fillColor=none;'
        attrs=dict(id=ident,value=value.replace('\n','<br>'),style=style,vertex='1',parent='1',kind=kind)
        if ident.startswith('u'): attrs['useCase']=ident[1:]
        if kind=='actor': attrs['role']=ident
        cell=ET.SubElement(self.root,'mxCell',**attrs)
        ET.SubElement(cell,'mxGeometry',x=str(x),y=str(y),width=str(w),height=str(h),**{'as':'geometry'})
        self.nodes[ident]=(x,y,w,h,kind)
        return ident

    def uc(self,n,x,y,w=270,h=95):
        return self.box('u'+str(n),f'UC{n:02}\n'+UC[n][0],x,y,w,h)
    def actor(self,role,x,y): return self.box(role,ACTORS[role],x,y,60,85,'actor',17 if x>1250 else 19)
    def boundary(self,label='Информационная система Sensei++'):
        self.box('system',label,235,110,1030,755,'boundary',22,True)
    def note(self,text,x=245,y=885,w=1010,h=70): self.box('note'+str(self.count),text,x,y,w,h,'note',18)

    def edge(self,source,target,kind='assoc',points=None,sides=(1,.5,0,.5),label=None):
        self.count+=1
        arrow='none' if kind=='assoc' else ('block' if kind=='generalization' else 'open')
        label=label if label is not None else (f'«{kind}»' if kind in ('include','extend') else '')
        sx,sy,tx,ty=sides
        style=f'edgeStyle=none;rounded=0;html=1;fontFamily=Times New Roman;fontSize=18;labelBackgroundColor=#ffffff;strokeColor=#000000;strokeWidth=1.4;endArrow={arrow};endFill=0;startArrow=none;exitX={sx};exitY={sy};entryX={tx};entryY={ty};exitPerimeter=0;entryPerimeter=0;'
        if kind in ('include','extend'): style+='dashed=1;dashPattern=6 4;'
        c=ET.SubElement(self.root,'mxCell',id='e'+str(self.count),value=label,style=style,edge='1',parent='1',source=source,target=target,relation=kind)
        g=ET.SubElement(c,'mxGeometry',relative='1',**{'as':'geometry'})
        # Give short horizontal dependencies enough room for their stereotypes.
        # This label offset is persisted for diagrams.net and used by the preview.
        if label and not points and sy==ty==.5:
            a,b=self.nodes[source],self.nodes[target]
            mid_y=(a[1]+a[3]/2+b[1]+b[3]/2)/2
            offset=min(a[1],b[1])-18-mid_y
            ET.SubElement(g,'mxPoint',x='0',y=str(offset),**{'as':'offset'})
        if points:
            arr=ET.SubElement(g,'Array',**{'as':'points'})
            for x,y in points: ET.SubElement(arr,'mxPoint',x=str(x),y=str(y))
    def assoc(self,role,nums,channel=215,side='left'):
        for n in nums:
            ax,ay,aw,ah,_=self.nodes[role]; x,y,w,h,_=self.nodes['u'+str(n)]
            if side=='left': self.edge(role,'u'+str(n),points=[(channel,ay+ah*.5),(channel,y+h*.5)])
            else: self.edge(role,'u'+str(n),points=[(channel,ay+ah*.5),(channel,y+h*.5)],sides=(0,.5,1,.5))

